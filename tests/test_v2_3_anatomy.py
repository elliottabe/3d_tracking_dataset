"""Invariants for the v2_3 anatomy config and its compiled MuJoCo model.

These guard the three things that silently break a non-v1 anatomy run:
keypoint column order (STAC matches columns positionally), the MJX-incompatible
adhesion actuators, and the missing tracking[...] sites.

The anatomy config points at a *derived*, adhesion-free model
(``models/fruitfly_v2_3_ik/fruitfly_v2_3_ik.xml``, generated by
``scripts/models/build_v2_3_ik_model.py``) rather than the shared
body-model repo directly: the shared repo's model keeps its 8 adhesion
actuators enabled on purpose (fruitfly_body_models commit 072a293) because
warp-backend training/rollout needs them and stripping them breaks trained
checkpoints. The derived model is kinematically identical to the shared one
except for `nu` -- see test_derived_model_kinematically_identical_to_shared
and test_shared_model_still_has_adhesion_actuators below.
"""
from __future__ import annotations

from pathlib import Path

import mujoco as mj
import numpy as np
import pytest
from omegaconf import OmegaConf

REPO = Path(__file__).resolve().parents[1]
BODY = Path('/gscratch/portia/eabe/Research/MyRepos/fly_neuromech/fruitfly_body_models')
SHARED_V2_3_XML = BODY / 'fruitfly_v2.3' / 'fruitfly_muscles_warp.xml'
V2_3_XML = REPO / 'models' / 'fruitfly_v2_3_ik' / 'fruitfly_v2_3_ik.xml'


def _cfg(name):
    return OmegaConf.load(REPO / 'configs' / 'anatomy' / f'{name}.yaml')


def _model():
    return mj.MjModel.from_xml_path(str(V2_3_XML))


def _shared_model():
    return mj.MjModel.from_xml_path(str(SHARED_V2_3_XML))


def test_name_and_paths():
    raw = OmegaConf.to_container(_cfg('v2_3'), resolve=False)
    assert raw['name'] == 'v2_3'
    assert raw['mjcf_path'].endswith('fruitfly_v2_3_ik/fruitfly_v2_3_ik.xml')
    assert raw['arena_path'].endswith('fruitfly_v2_3_ik/floor.xml')


def test_kp_names_order_identical_to_v1():
    """STAC matches keypoint columns POSITIONALLY once prune_model_to_available
    early-returns on an exact name-set match, so order is load-bearing."""
    assert list(_cfg('v2_3').model.KP_NAMES) == list(_cfg('v1').model.KP_NAMES)


def test_keypoint_model_pairs_key_order_identical_to_v2_muscles():
    assert (list(_cfg('v2_3').model.KEYPOINT_MODEL_PAIRS)
            == list(_cfg('v2_muscles').model.KEYPOINT_MODEL_PAIRS))


def test_tatip_offsets_are_left_right_mirrored():
    """v2_muscles.yaml has T3L_TaTip mirrored onto the right side; v2_3 fixes it."""
    offs = _cfg('v2_3').model.KEYPOINT_INITIAL_OFFSETS
    for leg in ('T1', 'T2', 'T3'):
        left = [float(x) for x in str(offs[f'{leg}L_TaTip']).split()]
        right = [float(x) for x in str(offs[f'{leg}R_TaTip']).split()]
        assert left == [0.0, 0.005, 0.0], f'{leg}L_TaTip should be +y'
        assert right == [0.0, -0.005, 0.0], f'{leg}R_TaTip should be -y'


def test_every_mapped_body_exists_in_model():
    m = _model()
    bodies = {mj.mj_id2name(m, mj.mjtObj.mjOBJ_BODY, i) for i in range(m.nbody)}
    missing = {k: v for k, v in _cfg('v2_3').model.KEYPOINT_MODEL_PAIRS.items()
               if v not in bodies}
    assert not missing, f'bodies absent from v2.3: {missing}'


def test_declared_joint_names_exist_in_model():
    m = _model()
    joints = {mj.mj_id2name(m, mj.mjtObj.mjOBJ_JOINT, i) for i in range(m.njnt)}
    missing = [j for j in _cfg('v2_3').joint_names if j not in joints]
    assert not missing, f'joint_names absent from v2.3: {missing}'


def test_haltere_joints_declared():
    names = list(_cfg('v2_3').joint_names)
    assert 'haltere_left' in names and 'haltere_right' in names


def test_model_kinematic_shape():
    m = _model()
    assert (m.nq, m.nv, m.nbody, m.njnt) == (101, 100, 74, 95)


def test_no_body_transmission_actuators():
    """mjTRN_BODY (adhesion) actuators make mjx.put_model raise."""
    m = _model()
    assert int((m.actuator_trntype == mj.mjtTrn.mjTRN_BODY).sum()) == 0
    assert m.nu == 264


def test_has_50_tracking_sites_matching_config():
    m = _model()
    names = [mj.mj_id2name(m, mj.mjtObj.mjOBJ_SITE, i) for i in range(m.nsite)]
    tracking = [n for n in names if n and n.startswith('tracking[')]
    assert len(tracking) == 50
    got = {n[len('tracking['):-1] for n in tracking}
    assert got == set(_cfg('v2_3').model.KP_NAMES)


def test_tracking_sites_attached_to_mapped_bodies():
    m = _model()
    pairs = _cfg('v2_3').model.KEYPOINT_MODEL_PAIRS
    for kp, body in pairs.items():
        sid = mj.mj_name2id(m, mj.mjtObj.mjOBJ_SITE, f'tracking[{kp}]')
        assert sid >= 0, f'missing site for {kp}'
        parent = mj.mj_id2name(m, mj.mjtObj.mjOBJ_BODY, m.site_bodyid[sid])
        assert parent == body, f'{kp} on {parent}, expected {body}'


def test_model_loads_into_mjx():
    """The end-to-end guard: postprocess_stac_data.py calls mjx.put_model."""
    from mujoco import mjx
    mjx.put_model(_model())


def _names(m, obj_type):
    return [mj.mj_id2name(m, obj_type, i) for i in range(getattr(m, {
        mj.mjtObj.mjOBJ_JOINT: 'njnt',
        mj.mjtObj.mjOBJ_BODY: 'nbody',
        mj.mjtObj.mjOBJ_SITE: 'nsite',
    }[obj_type]))]


def test_derived_model_kinematically_identical_to_shared():
    """The derived (adhesion-stripped) model must stay kinematically
    identical to the shared source it is generated from -- only `nu` may
    differ. Downstream code stores qpos/qvel/xpos/xquat, none of which depend
    on nu, so a derived model that diverges kinematically would silently
    corrupt any dataset built from it while still training/rolling out
    fine against the shared (272-actuator) checkpoints.
    """
    derived = _model()
    shared = _shared_model()

    assert (derived.nq, derived.nv, derived.nbody, derived.njnt) == \
        (shared.nq, shared.nv, shared.nbody, shared.njnt)
    assert derived.nsite == shared.nsite
    assert derived.ngeom == shared.ngeom

    # Only nu (actuator count) may differ -- that is the whole point of the
    # derived model.
    assert derived.nu != shared.nu
    assert derived.nu == 264
    assert shared.nu == 272

    assert _names(derived, mj.mjtObj.mjOBJ_JOINT) == _names(shared, mj.mjtObj.mjOBJ_JOINT)
    assert _names(derived, mj.mjtObj.mjOBJ_BODY) == _names(shared, mj.mjtObj.mjOBJ_BODY)
    assert _names(derived, mj.mjtObj.mjOBJ_SITE) == _names(shared, mj.mjtObj.mjOBJ_SITE)

    np.testing.assert_array_equal(derived.jnt_type, shared.jnt_type)
    np.testing.assert_array_equal(derived.jnt_range, shared.jnt_range)
    np.testing.assert_array_equal(derived.body_pos, shared.body_pos)
    np.testing.assert_array_equal(derived.body_quat, shared.body_quat)
    np.testing.assert_array_equal(derived.body_parentid, shared.body_parentid)

    # site_pos differs for exactly the two abdomen trunk markers we deliberately
    # re-placed onto the v2.3 meshes (they were inherited from v2.1: Abd_A4 sat
    # 0.0145 INSIDE the abdomen, Abd_tip 0.0159 PAST the tip). Everything else
    # must still match, and no OTHER site may drift.
    CORRECTED = {'tracking[Abd_A4]', 'tracking[Abd_tip]'}
    site_names = _names(derived, mj.mjtObj.mjOBJ_SITE)
    differs = {site_names[i] for i in range(derived.nsite)
               if not np.array_equal(derived.site_pos[i], shared.site_pos[i])}
    assert differs == CORRECTED, f'unexpected site drift: {differs ^ CORRECTED}'

    keep = [i for i in range(derived.nsite) if site_names[i] not in CORRECTED]
    np.testing.assert_array_equal(derived.site_pos[keep], shared.site_pos[keep])

    # Forward kinematics from a random qpos must agree exactly (bit-identical
    # kinematic trees, so no floating-point drift is expected either).
    rng = np.random.default_rng(0)
    qpos = rng.uniform(-0.2, 0.2, size=derived.nq)
    qpos[3:7] = [1.0, 0.0, 0.0, 0.0]  # keep the root freejoint quaternion valid

    d_derived = mj.MjData(derived)
    d_derived.qpos[:] = qpos
    mj.mj_kinematics(derived, d_derived)

    d_shared = mj.MjData(shared)
    d_shared.qpos[:] = qpos
    mj.mj_kinematics(shared, d_shared)

    assert np.abs(d_derived.xpos - d_shared.xpos).max() == 0.0
    assert np.abs(d_derived.xquat - d_shared.xquat).max() == 0.0


def test_shared_model_still_has_adhesion_actuators():
    """Regression guard: fruitfly_body_models commit 072a293 restored the 8
    adhesion actuators in the shared repo on purpose (warp backend needs
    them; stripping breaks trained checkpoints). This project must never
    strip them upstream again -- the adhesion-free variant belongs only in
    the derived model built by scripts/models/build_v2_3_ik_model.py.
    """
    m = _shared_model()
    assert int((m.actuator_trntype == mj.mjtTrn.mjTRN_BODY).sum()) == 8
    assert m.nu == 272
