#!/usr/bin/env python3
"""
Submit the courtship mesh-silhouette inference pipeline (Tasks 1-9) as a chain
of SLURM jobs with a dependency chain:

    [Stage-0 SAM3 array]  ->  precompute  ->  JAX array (per bout)  ->  aggregate
     (PyTorch, optional)      (offsets +      (run_courtship_bout.py)   (session
                               decimated mesh)                          QC dash)

Stage-0 SAM3 is skipped entirely when every discovered bout under
`recording.predictions_dir` already has a `sam3_masks.npz` (the common case on
Session0, where masks were generated by an earlier shard run) -- see
`scripts/slurm_predict_session.py` for the same SAM3 body / cu13 CUDA-lib
pattern reused here.

Companion to scripts/slurm_train_vit.py / scripts/slurm_predict_session.py
(same launcher pattern: `compose_cfg` reads `slurm`/`recording`/`outputs` at
submit time, `sbatch --parsable` captures job ids for `--dependency=afterok`).

Preemption resume
-----------------
ckpt* partitions are preemptible, so the JAX array (and the single-job
precompute step) are submitted with `--requeue`. Every array task writes to a
deterministic `<outputs.out>/bouts/bout_<idx:05d>/fly<f>/` derived from the
(fixed) array task id, so a preempt+requeue lands in the same directory and
`jarvis_jax.cse.courtship_resume` skips already-completed stages (see
`scripts/run_courtship_bout.py`). Re-running this submitter after a partial
array failure is safe: SAM3 (`reuse_masks=true`) and every bout stage are
idempotent, so only unfinished work is redone.

Usage:
    # Submit the full chain for Session0 on ckpt-g2 (masks assumed present):
    python scripts/slurm_courtship_array.py

    # A different slurm profile + Hydra overrides (both forwarded to every
    # job's python command):
    python scripts/slurm_courtship_array.py --slurm gpu_l40s \\
        outputs.out=/gscratch/portia/eabe/data/Johnson_lab/courtship/Session0_bouts_070326

    # See the scripts + dependency chain without submitting:
    python scripts/slurm_courtship_array.py --dry-run
"""

import argparse
import glob
import os
import re
import subprocess
import sys
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
PKG_DIR = PROJECT_DIR / "third_party" / "jarvis_jax"
CONFIG_DIR = PROJECT_DIR / "configs"


# ---------------------------------------------------------------------------
# Bout discovery
# ---------------------------------------------------------------------------

def bout_indices(predictions_dir: str) -> list[int]:
    """Sorted bout indices discovered as bout_<idx> dirs under predictions_dir
    (mirrors scripts/run_courtship_bout.py::_bout_dirs)."""
    idxs = []
    for d in sorted(glob.glob(os.path.join(predictions_dir, "bout_*"))):
        m = re.match(r"bout_(\d+)$", os.path.basename(d))
        if m:
            idxs.append(int(m.group(1)))
    return sorted(idxs)


def missing_sam3_masks(predictions_dir: str, idxs: list[int]) -> list[int]:
    """Bout indices under predictions_dir lacking a sam3_masks.npz."""
    return [i for i in idxs
            if not os.path.exists(os.path.join(predictions_dir, f"bout_{i:05d}", "sam3_masks.npz"))]


# ---------------------------------------------------------------------------
# Pure sbatch-script builders (unit-tested; no SLURM/filesystem access)
# ---------------------------------------------------------------------------

def build_sam3_array_script(
    *,
    job_name: str,
    partition: str,
    account: str,
    cpus: int,
    mem: int,
    gpus: int,
    time_limit: str,
    requeue: bool,
    conda_env: str,
    n_bouts: int,
    session_dir: str,
    masks_out: str,
    dependency: str = "",
) -> str:
    """Stage-0 SAM3 mask+identity array (PyTorch env, cu13 CUDA libs).

    One array task per bout (0..n_bouts-1); `sam3.reuse_masks=true` skips
    bouts whose sam3_masks.npz already exists, so this is cheap to resubmit
    and safe even when only a handful of bouts are actually missing masks.
    """
    requeue_line = "#SBATCH --requeue" if requeue else ""
    dependency_line = f"#SBATCH --dependency={dependency}" if dependency else ""
    return f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --partition={partition}
#SBATCH --account={account}
#SBATCH --time={time_limit}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --gpus={gpus}
#SBATCH --mem={mem}G
#SBATCH --array=0-{n_bouts - 1}
#SBATCH --open-mode=append
#SBATCH -o {masks_out}/slurm-sam3-%A_%a.out
{dependency_line}
{requeue_line}
set -x
source ~/.bashrc
micromamba activate {conda_env}
export LD_PRELOAD="$CONDA_PREFIX/lib/libstdc++.so.6"
export LD_LIBRARY_PATH="$CONDA_PREFIX/lib/python3.12/site-packages/nvidia/cu13/lib"
echo "Node: $SLURMD_NODENAME  job: $SLURM_JOB_ID  task: $SLURM_ARRAY_TASK_ID"
cd {PKG_DIR}
python -u scripts/sam3_masks.py sam3.session_dir={session_dir} sam3.out={masks_out} \\
    sam3.bout_ids=${{SLURM_ARRAY_TASK_ID}} sam3.sam3_compile=false sam3.reuse_masks=true
"""


def build_precompute_script(
    *,
    job_name: str,
    partition: str,
    account: str,
    cpus: int,
    mem: int,
    gpus: int,
    time_limit: str,
    requeue: bool,
    conda_env: str,
    run_dir: str,
    config_name: str,
    overrides: str,
    dependency: str = "",
) -> str:
    """Single (non-array) job: fit-once STAC offsets + decimated mesh.

    Runs run_courtship_bout.py restricted to bout 0 (both flies). Stages A-E
    are stage-checkpointed (jarvis_jax.cse.courtship_resume), so this both
    seeds offsets.h5/decimated_mesh.npz (which every array task reads
    read-only) AND fully finishes bout 0 -- the JAX array's task 0 then finds
    it already DONE and skips instantly.
    """
    requeue_line = "#SBATCH --requeue" if requeue else ""
    dependency_line = f"#SBATCH --dependency={dependency}" if dependency else ""
    return f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --partition={partition}
#SBATCH --account={account}
#SBATCH --time={time_limit}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --gpus={gpus}
#SBATCH --mem={mem}G
#SBATCH --open-mode=append
#SBATCH -o {run_dir}/slurm-precompute-%j.out
{dependency_line}
{requeue_line}
set -x
source ~/.bashrc
micromamba activate {conda_env}
unset LD_LIBRARY_PATH                       # let JAX use its bundled CUDA wheels
export XLA_PYTHON_CLIENT_MEM_FRACTION=0.9
echo "Node: $SLURMD_NODENAME  job: $SLURM_JOB_ID"
cd {PROJECT_DIR}
python -u scripts/run_courtship_bout.py --config-name={config_name} ++bout_ids=0{overrides}
"""


def build_jax_array_script(
    *,
    job_name: str,
    partition: str,
    account: str,
    cpus: int,
    mem: int,
    gpus: int,
    time_limit: str,
    requeue: bool,
    conda_env: str,
    n_bouts: int,
    run_dir: str,
    config_name: str,
    overrides: str,
    dependency: str = "",
) -> str:
    """JAX array over bouts: run_courtship_bout.py +bout_ids=$SLURM_ARRAY_TASK_ID.

    One array task per bout (0..n_bouts-1); every stage inside is
    checkpointed, so --requeue on a preemptible partition resumes cleanly.
    """
    requeue_line = "#SBATCH --requeue" if requeue else ""
    dependency_line = f"#SBATCH --dependency={dependency}" if dependency else ""
    return f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --partition={partition}
#SBATCH --account={account}
#SBATCH --time={time_limit}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --gpus={gpus}
#SBATCH --mem={mem}G
#SBATCH --array=0-{n_bouts - 1}
#SBATCH --open-mode=append
#SBATCH -o {run_dir}/slurm-jax-%A_%a.out
{dependency_line}
{requeue_line}
set -x
source ~/.bashrc
micromamba activate {conda_env}
unset LD_LIBRARY_PATH                       # let JAX use its bundled CUDA wheels
export XLA_PYTHON_CLIENT_MEM_FRACTION=0.9
echo "Node: $SLURMD_NODENAME  job: $SLURM_JOB_ID  task: $SLURM_ARRAY_TASK_ID"
cd {PROJECT_DIR}
python -u scripts/run_courtship_bout.py --config-name={config_name} ++bout_ids=${{SLURM_ARRAY_TASK_ID}}{overrides}
"""


def build_aggregate_script(
    *,
    job_name: str,
    partition: str,
    account: str,
    cpus: int,
    mem: int,
    time_limit: str,
    conda_env: str,
    run_dir: str,
    out_root: str,
    dependency: str = "",
) -> str:
    """Cheap CPU-only job: merge every bout/fly qc.json into a session
    dashboard (jarvis_jax.cse.courtship_qc.aggregate_session_qc).

    The aggregation logic is written to <run_dir>/aggregate_qc.py via a
    quote-delimited heredoc (`<<'PYEOF'`, so bash performs zero variable/
    quote expansion on the body) and then run as a plain `python <file>` --
    NOT an inline `python -c "..."`. An inline double-quoted `-c "..."` is
    unsafe here because the aggregation source itself needs double-quoted
    dict keys (e.g. summ["n_bouts_flies"]); bash would strip those `"` before
    python ever saw them, turning it into the bareword `summ[n_bouts_flies]`
    -> NameError. All path substitutions (out_root, PKG_DIR) are baked in
    up front via repr() from the outer f-string, so the emitted python has
    no runtime string formatting of its own to trip over.
    """
    dependency_line = f"#SBATCH --dependency={dependency}" if dependency else ""
    agg_py = (
        "import glob, sys\n"
        f"sys.path.insert(0, {str(PKG_DIR)!r})\n"
        "from jarvis_jax.cse.courtship_qc import aggregate_session_qc\n"
        f"paths = sorted(glob.glob({out_root!r} + '/bouts/bout_*/fly*/qc.json'))\n"
        f"summ = aggregate_session_qc(paths, {out_root!r} + '/qc/session_qc.json',\n"
        f"                            plot_dir={out_root!r} + '/qc/dashboard')\n"
        "print('[aggregate]', summ[\"n_bouts_flies\"], 'bout/fly qc files ->', "
        f"{out_root!r} + '/qc/session_qc.json')\n"
    )
    return f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --partition={partition}
#SBATCH --account={account}
#SBATCH --time={time_limit}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}G
#SBATCH --open-mode=append
#SBATCH -o {run_dir}/slurm-aggregate-%j.out
{dependency_line}
set -x
source ~/.bashrc
micromamba activate {conda_env}
cd {PROJECT_DIR}
mkdir -p {run_dir}
cat > {run_dir}/aggregate_qc.py <<'PYEOF'
{agg_py}PYEOF
python -u {run_dir}/aggregate_qc.py
"""


# ---------------------------------------------------------------------------
# Submission plumbing
# ---------------------------------------------------------------------------

def compose_cfg(config_name: str, slurm: str, passthrough: list[str]):
    """Compose the repo-root Hydra config at submit time to read
    recording/outputs/slurm values (mirrors slurm_train_vit.py::compose_cfg,
    but against configs/ at the repo root, not jarvis_jax's own config dir --
    see third_party/jarvis_jax/tests/test_courtship_config.py for the same
    initialize_config_dir(config_dir=<repo>/configs) pattern)."""
    from hydra import initialize_config_dir, compose
    overrides = [f"slurm={slurm}"] + list(passthrough)
    with initialize_config_dir(version_base=None, config_dir=str(CONFIG_DIR)):
        cfg = compose(config_name=config_name, overrides=overrides)
    return cfg


def slurm_submit(script: str, *, dependency: str | None = None) -> str:
    """Submit a job script via stdin (sbatch --parsable) and return its job id."""
    cmd = ["sbatch", "--parsable"]
    if dependency:
        cmd.append(f"--dependency={dependency}")
    try:
        out = subprocess.check_output(cmd, input=script, universal_newlines=True)
        return out.strip().split(";")[0].split()[-1]
    except subprocess.CalledProcessError as e:
        print(f"Error submitting job: {e.output}", file=sys.stderr)
        sys.exit(1)


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--config-name', default='courtship_pipeline',
                   help='Hydra config name under configs/ (default: courtship_pipeline)')
    p.add_argument('--slurm', default='ckpt_g2',
                   help='Hydra slurm config group (default: ckpt_g2)')
    p.add_argument('--dry-run', action='store_true',
                   help='Print the scripts + dependency chain without submitting')
    args, passthrough = p.parse_known_args()

    if not PKG_DIR.is_dir():
        print(f"Error: jarvis_jax package not found at {PKG_DIR}", file=sys.stderr)
        sys.exit(1)

    cfg = compose_cfg(args.config_name, args.slurm, passthrough)
    sl = cfg.slurm
    predictions_dir = str(cfg.recording.predictions_dir)
    session_dir = str(cfg.recording.session_dir)
    run_root = str(cfg.outputs.out)
    name = str(cfg.recording.name)

    # Bout count reads the filesystem (predictions_dir); guard so --dry-run
    # still demos the scripts even if that path is unreachable/empty.
    try:
        idxs = bout_indices(predictions_dir)
        n_bouts = len(idxs)
        missing = missing_sam3_masks(predictions_dir, idxs)
    except OSError as e:
        idxs, n_bouts, missing = [], 0, []
        print(f"Warning: could not list bouts under {predictions_dir}: {e}", file=sys.stderr)

    if n_bouts == 0:
        if args.dry_run:
            print(f"Warning: no bout_* dirs found under {predictions_dir}; "
                  f"using n_bouts=1 for the dry-run script demo.")
            n_bouts, missing = 1, [0]
        else:
            print(f"Error: no bout_* dirs found under {predictions_dir}", file=sys.stderr)
            sys.exit(1)

    overrides_str = (" " + " ".join(passthrough)) if passthrough else ""
    gpus = int(sl.gpus_per_task)
    requeue = bool(sl.requeue)

    print(f"Session : {name}  ({predictions_dir})")
    print(f"Bouts   : {n_bouts} discovered, {len(missing)} missing sam3_masks.npz")
    print(f"Out     : {run_root}")
    print(f"Compute : {sl.partition}, {gpus} GPU(s)/task, "
          f"{'requeue on' if requeue else 'requeue off'}")
    if passthrough:
        print(f"Overrides: {' '.join(passthrough)}")

    submitted = {}  # stage -> job id (real submit) or a printable placeholder (dry-run)

    def _run(stage: str, script: str, dependency: str | None):
        print(f"\n--- {stage} script{' (dry-run)' if args.dry_run else ''} ---")
        print(script)
        if args.dry_run:
            submitted[stage] = f"<{stage}_JOBID>"
            return
        jid = slurm_submit(script, dependency=dependency)
        submitted[stage] = jid
        print(f"Submitted {stage}: {jid}"
              f"{f'  (dependency={dependency})' if dependency else ''}")

    # (a)/(b) Stage-0 SAM3 array -- only when some bout lacks sam3_masks.npz.
    sam3_dep = None
    if missing:
        sam3_job = f"sam3ct_{name}"[:60]
        sam3_script = build_sam3_array_script(
            job_name=sam3_job, partition=sl.partition, account=sl.account,
            cpus=sl.cpus, mem=sl.mem, gpus=gpus, time_limit=sl.time,
            requeue=requeue, conda_env=sl.conda_env,
            n_bouts=n_bouts, session_dir=session_dir, masks_out=predictions_dir)
        _run("sam3", sam3_script, None)
        sam3_dep = f"afterok:{submitted['sam3']}"
    else:
        print("\nSAM3: skipped (every discovered bout already has sam3_masks.npz)")

    # (c) precompute (offsets fit-once + decimated mesh), gated on SAM3.
    precompute_job = f"ctprecomp_{name}"[:60]
    precompute_script = build_precompute_script(
        job_name=precompute_job, partition=sl.partition, account=sl.account,
        cpus=sl.cpus, mem=sl.mem, gpus=gpus, time_limit=sl.time,
        requeue=requeue, conda_env=sl.conda_env, run_dir=run_root,
        config_name=args.config_name, overrides=overrides_str,
        dependency=sam3_dep or "")
    _run("precompute", precompute_script, sam3_dep)

    # (d) JAX array over bouts, gated on precompute, --requeue.
    jax_dep = f"afterok:{submitted['precompute']}"
    jax_job = f"ctjax_{name}"[:60]
    jax_script = build_jax_array_script(
        job_name=jax_job, partition=sl.partition, account=sl.account,
        cpus=sl.cpus, mem=sl.mem, gpus=gpus, time_limit=sl.time,
        requeue=requeue, conda_env=sl.conda_env, n_bouts=n_bouts,
        run_dir=run_root, config_name=args.config_name, overrides=overrides_str,
        dependency=jax_dep)
    _run("jax_array", jax_script, jax_dep)

    # (e) aggregation, gated on the JAX array.
    agg_dep = f"afterok:{submitted['jax_array']}"
    agg_job = f"ctagg_{name}"[:60]
    agg_script = build_aggregate_script(
        job_name=agg_job, partition=sl.partition, account=sl.account,
        cpus=sl.cpus, mem=sl.mem, time_limit=sl.time, conda_env=sl.conda_env,
        run_dir=run_root, out_root=run_root, dependency=agg_dep)
    _run("aggregate", agg_script, agg_dep)

    if not args.dry_run:
        Path(run_root).mkdir(parents=True, exist_ok=True)
        print(f"\nDependency chain: "
              f"{'sam3(' + submitted['sam3'] + ') -> ' if 'sam3' in submitted else ''}"
              f"precompute({submitted['precompute']}) -> "
              f"jax_array({submitted['jax_array']}) -> aggregate({submitted['aggregate']})")
        print(f"Monitor : squeue -u $USER")


if __name__ == "__main__":
    main()
