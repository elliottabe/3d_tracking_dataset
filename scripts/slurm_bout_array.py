def compose_cfg(config_name: str, slurm: str, passthrough: list[str]):
    """Compose the repo-root Hydra config at submit time to read
    recording/outputs/slurm values (mirrors slurm_train_vit.py::compose_cfg,
    but against configs/ at the repo root, not jarvis_jax's own config dir --
    see third_party/jarvis_jax/tests/test_courtship_config.py for the same
    initialize_config_dir(config_dir=<repo>/configs) pattern)."""
    from hydra import initialize_config_dir, compose
    overrides = [f"slurm={slurm}"] + list(passthrough)
    with initialize_config_dir(version_base=None, config_dir=str(CONFIG_DIR)):
        cfg = compose(config_name=config_name, overrides=overrides)
    return cfg


def slurm_submit(script: str, *, dependency: str | None = None) -> str:
    """Submit a job script via stdin (sbatch --parsable) and return its job id."""
    cmd = ["sbatch", "--parsable"]
    if dependency:
        cmd.append(f"--dependency={dependency}")
    try:
        out = subprocess.check_output(cmd, input=script, universal_newlines=True)
        return out.strip().split(";")[0].split()[-1]
    except subprocess.CalledProcessError as e:
        print(f"Error submitting job: {e.output}", file=sys.stderr)
        sys.exit(1)


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--config-name', default='pipeline',
                   help='Hydra config name under configs/ (default: pipeline)')
    p.add_argument('--slurm', default='ckpt_all',
                   help='Hydra slurm config group (default: ckpt_g2)')
    p.add_argument('--bouts', default=None,
                   help="comma-separated bout indices to submit (default: every "
                        "bout_* dir under recording.predictions_dir). Use when "
                        "re-running a SUBSET, e.g. the bouts a QC pass flagged, "
                        "so the array does not queue a task per already-good "
                        "bout. Indices not present under predictions_dir are an "
                        "error rather than a silent no-op.")
    p.add_argument('--lifter', default='dlt', choices=('dlt', 'mvq'),
                   help="Which code produces kp2d/kp3d. 'dlt' (default) is the "
                        "SAM3 -> ViTPose -> DLT chain. 'mvq' replaces Stages A+B "
                        "with an mvq lift array (scripts/mvq_lift_bout.py) placed "
                        "before precompute, skips the SAM3 stage entirely (masks "
                        "are an INPUT there), and passes pipeline.lifter=mvq plus "
                        "the --mvq-config group to every run_bout.py command.")
    p.add_argument('--mvq-lift', default='array', choices=('array', 'skip'),
                   help="With --lifter mvq: 'array' (default) queues the lift as a "
                        "GPU array before precompute. 'skip' assumes the lift has "
                        "already run -- e.g. scripts/slurm/mvq_p3a_campaign.sh "
                        "--local-gpus N lifted the recording on an interactive node "
                        "to dodge the queue -- and chains precompute -> IK -> "
                        "aggregate straight off the existing kp3d.npz files. It is "
                        "still safe if a bout was missed: run_bout.py's Stage A/B "
                        "would then RE-DERIVE that bout with the DLT chain, so the "
                        "skip is checked below rather than trusted.")
    p.add_argument('--mvq-config', default='p3a',
                   help='configs/mvq/<name>.yaml -- the checkpoint/exist_thresh '
                        'block. The SAME values reach the lift array and '
                        "run_bout.py, so the lifter's gates string is exactly what "
                        "Stage B's staleness check recomputes.")
    p.add_argument('--dry-run', action='store_true',
                   help='Print the scripts + dependency chain without submitting')
    args, passthrough = p.parse_known_args()

    # The lifter selection is a CONFIG fact, not just a submitter flag: it has to
    # reach run_bout.py (else Stage B would recompute DLT keypoints over the
    # lifted ones) AND compose_cfg here (else cfg.mvq is None and the lift array
    # has no checkpoint to name). One place sets both.
    if args.lifter == 'mvq':
        passthrough = list(passthrough) + [f'mvq={args.mvq_config}',
                                           'pipeline.lifter=mvq']

    if not PKG_DIR.is_dir():
        print(f"Error: jarvis_jax package not found at {PKG_DIR}", file=sys.stderr)
        sys.exit(1)

    cfg = compose_cfg(args.config_name, args.slurm, passthrough)
    sl = cfg.slurm
    predictions_dir = str(cfg.recording.predictions_dir)
    session_dir = str(cfg.recording.session_dir)
    run_root = str(cfg.outputs.out)
    name = str(cfg.recording.name)

    # Desync gate: generate <session_dir>/sync_plan.json (idempotent) so the SAM3 +
    # courtship workers consume it. Clean/no-meta recordings are unaffected.
    try:
        import sys as _sys
        _sys.path.insert(0, str(PKG_DIR))
        from jarvis_jax.predict.sam3_driver import ensure_sync_plan
        _plan = ensure_sync_plan(session_dir)
        print(f"[sync] {name}: plan status={getattr(_plan, 'status', 'none')}")
    except Exception as e:  # noqa: BLE001 -- gate is best-effort at submit time
        print(f"[sync] {name}: plan generation skipped ({type(e).__name__}: {e})")

    # Bout count reads the filesystem (predictions_dir); guard so --dry-run
    # still demos the scripts even if that path is unreachable/empty.
    try:
        idxs = bout_indices(predictions_dir)
        if args.bouts is not None:
            want = [int(x) for x in str(args.bouts).split(',') if x.strip() != '']
            unknown = sorted(set(want) - set(idxs))
            if unknown and not args.dry_run:
                print(f"Error: bout(s) {unknown} not found under {predictions_dir}",
                      file=sys.stderr)
                sys.exit(1)
            idxs = [i for i in idxs if i in set(want)]
            print(f"[subset] {name}: submitting {len(idxs)} of "
                  f"{len(bout_indices(predictions_dir))} bouts: {idxs}")
        n_bouts = len(idxs)
        missing = missing_sam3_masks(predictions_dir, idxs)
    except OSError as e:
        idxs, n_bouts, missing = [], 0, []
        print(f"Warning: could not list bouts under {predictions_dir}: {e}", file=sys.stderr)

    if n_bouts == 0:
        if args.dry_run:
            print(f"Warning: no bout_* dirs found under {predictions_dir}; "
                  f"using idxs=[1] for the dry-run script demo.")
            idxs, missing = [1], [1]
            n_bouts = len(idxs)
        else:
            print(f"Error: no bout_* dirs found under {predictions_dir}", file=sys.stderr)
            sys.exit(1)

    # shlex.quote each override: they are pasted verbatim into a bash script,
    # and an unquoted Hydra value can change meaning there. Measured: a
    # `recording.timestamp="2026_04_02_17_28_34"` that was correctly quoted on
    # the submit command line arrived in the sbatch script bare, so Hydra read
    # it as an INT (underscores are digit separators) and every job looked for
    # .../Session1/20260402172834/calibration and died with FileNotFoundError.
    overrides_str = ((" " + " ".join(shlex.quote(p) for p in passthrough))
                     if passthrough else "")
    gpus = int(sl.gpus_per_task)
    requeue = bool(sl.requeue)

    print(f"Session : {name}  ({predictions_dir})")
    print(f"Bouts   : {n_bouts} discovered, {len(missing)} missing sam3_masks.npz")
    print(f"Out     : {run_root}")
    print(f"Compute : {sl.partition}, {gpus} GPU(s)/task, "
          f"{'requeue on' if requeue else 'requeue off'}")
    if passthrough:
        print(f"Overrides: {' '.join(passthrough)}")

    submitted = {}  # stage -> job id (real submit) or a printable placeholder (dry-run)

    def _run(stage: str, script: str, dependency: str | None):
        print(f"\n--- {stage} script{' (dry-run)' if args.dry_run else ''} ---")
        print(script)
        if args.dry_run:
            submitted[stage] = f"<{stage}_JOBID>"
            return
        jid = slurm_submit(script, dependency=dependency)
        submitted[stage] = jid
        print(f"Submitted {stage}: {jid}"
              f"{f'  (dependency={dependency})' if dependency else ''}")

    # (a)/(b) Stage-0 SAM3 array -- only when some bout lacks sam3_masks.npz.
    # With --lifter mvq the masks are an INPUT (the lift places its crops from
    # their centroids and never re-segments), so a missing one is an error to
    # report rather than work to queue.
    sam3_dep = None
    if args.lifter == 'mvq' and missing:
        print(f"Error: --lifter mvq consumes existing SAM3 masks, but {len(missing)} "
              f"of {n_bouts} bouts lack sam3_masks.npz: {missing[:10]}", file=sys.stderr)
        if not args.dry_run:
            sys.exit(1)
    elif args.lifter == 'mvq':
        print("\nSAM3: skipped (--lifter mvq consumes the existing masks)")
    elif missing:
        sam3_job = f"sam3ct_{name}"[:60]
        sam3_script = build_sam3_array_script(
            job_name=sam3_job, partition=sl.partition, account=sl.account,
            cpus=sl.cpus, mem=sl.mem, gpus=gpus, time_limit=sl.time,
        constraint=str(sl.get("constraint", "") or ""),
            requeue=requeue, conda_env=sl.conda_env,
            idxs=idxs, session_dir=session_dir, masks_out=predictions_dir,
            num_animals=int(cfg.recording.num_animals),
            bouts_csv=str(cfg.recording.get("bouts_csv", "") or ""))
        _run("sam3", sam3_script, None)
        sam3_dep = f"afterok:{submitted['sam3']}"
    else:
        print("\nSAM3: skipped (every discovered bout already has sam3_masks.npz)")

    # (b2) mvq lift array -- BEFORE precompute on purpose. The body-scale
    #      precompute pools scale.json over every bout of the recording that is
    #      already triangulated; lifting the whole recording first means it
    #      pools all of them instead of the one bout it was seeded with (the
    #      scale-from-first-bout defect, measured 15.5% low on Session0).
    if args.lifter == 'mvq' and args.mvq_lift == 'skip':
        # The lift already ran (locally, on an interactive node). Verify rather
        # than trust: an npz-only check would pass a bout whose lift was
        # interrupted between writing kp3d.npz and sex.json, and precompute
        # would then silently fall back to a shared body scale (see MEMORY
        # scale-from-first-bout-defect). `bout_lift_is_current` is the same
        # predicate the lifter itself uses to decide whether a bout is
        # already done, so reuse it here instead of a weaker local check.
        sys.path.insert(0, str(PKG_DIR))
        from jarvis_jax.tracking.lift_mvq import (bout_lift_is_current, mvq_gate_string,
                                                  resolve_mask_identity)
        from jarvis_jax.tracking.sexing import read_sex_meta
        mv = cfg.get("mvq") or {}
        if not mv.get("checkpoint"):
            print(f"Error: --lifter mvq needs mvq.checkpoint; configs/mvq/"
                  f"{args.mvq_config}.yaml sets none", file=sys.stderr)
            sys.exit(2)

        def _gates_for(i):
            """This bout's gate string, with `mvq.identity` resolved against ITS
            masks -- the same resolution the lifter does. A bout whose masks
            carry no human id review runs (and is gated as) the sex head even
            under `identity: mask`; comparing it against the unresolved 'mask'
            string would call a finished lift missing, and comparing a
            'mask'-gated lift against a resolved 'sex' string would call a
            fallback lift done."""
            _sm = read_sex_meta(os.path.join(predictions_dir, f"bout_{i:05d}",
                                             "sam3_masks.npz"))
            _id, _ = resolve_mask_identity(mv.get("identity"), _sm)
            return mvq_gate_string(str(mv["checkpoint"]), step=mv.get("step"),
                                   exist_thresh=float(mv.get("exist_thresh", 0.5)),
                                   identity=_id)

        _not_current = [i for i in idxs
                        if not bout_lift_is_current(
                            os.path.join(run_root, "bouts", f"bout_{i:05d}"),
                            _gates_for(i))]
        if _not_current:
            print(f"Error: --mvq-lift skip, but {len(_not_current)} bout(s) are not a "
                  f"current mvq lift (kp3d.npz per fly matching these gates AND "
                  f"sex.json from the lifter) under {run_root}: "
                  f"{_not_current[:10]}", file=sys.stderr)
            if not args.dry_run:
                sys.exit(1)
        else:
            print(f"\nmvq lift: skipped ({len(idxs)} bouts already lifted under "
                  f"{run_root})")
    elif args.lifter == 'mvq':
        mv = cfg.get("mvq") or {}
        if not mv.get("checkpoint"):
            print(f"Error: --lifter mvq needs mvq.checkpoint; configs/mvq/"
                  f"{args.mvq_config}.yaml sets none", file=sys.stderr)
            sys.exit(2)
        mvq_script = build_mvq_lift_array_script(
            job_name=f"mvqlift_{name}"[:60], partition=sl.partition, account=sl.account,
            cpus=sl.cpus, mem=sl.mem, gpus=gpus, time_limit=sl.time,
            constraint=str(sl.get("constraint", "") or ""),
            requeue=requeue, conda_env=sl.conda_env, idxs=idxs,
            session_dir=session_dir, predictions_dir=predictions_dir, run_dir=run_root,
            checkpoint=str(mv["checkpoint"]), step=mv.get("step"),
            exist_thresh=float(mv.get("exist_thresh", 0.5)),
            batch=int(mv.get("batch", 8)),
            merge_dist_units=float(mv.get("merge_dist_units", 30.0)),
            identity=str(mv.get("identity", "mask")),
            mask_assign_units=float(mv.get("mask_assign_units", 10.0)),
            anatomy_cfg=f"configs/anatomy/{cfg.anatomy.name}.yaml",
            recording_cfg=f"configs/recording/{str(name).lower()}.yaml",
            bouts_csv=str(cfg.recording.get("bouts_csv", "") or ""),
            dependency=sam3_dep or "")
        _run("mvq_lift", mvq_script, sam3_dep)
        sam3_dep = f"afterok:{submitted['mvq_lift']}"

    # (c) precompute (offsets fit-once), gated on SAM3 (or on the mvq lift).
    precompute_job = f"ctprecomp_{name}"[:60]
    precompute_script = build_precompute_script(
        job_name=precompute_job, partition=sl.partition, account=sl.account,
        cpus=sl.cpus, mem=sl.mem, gpus=gpus, time_limit=sl.time,
        constraint=str(sl.get("constraint", "") or ""),
        requeue=requeue, conda_env=sl.conda_env, bout_id=idxs[0], run_dir=run_root,
        config_name=args.config_name, overrides=overrides_str,
        dependency=sam3_dep or "")
    _run("precompute", precompute_script, sam3_dep)

    # (d) JAX array over bouts, gated on precompute, --requeue.
    jax_dep = f"afterok:{submitted['precompute']}"
    jax_job = f"ctjax_{name}"[:60]
    jax_script = build_jax_array_script(
        job_name=jax_job, partition=sl.partition, account=sl.account,
        cpus=sl.cpus, mem=sl.mem, gpus=gpus, time_limit=sl.time,
        constraint=str(sl.get("constraint", "") or ""),
        requeue=requeue, conda_env=sl.conda_env, idxs=idxs,
        run_dir=run_root, config_name=args.config_name, overrides=overrides_str,
        dependency=jax_dep)
    _run("jax_array", jax_script, jax_dep)

    # (e) aggregation, gated on the JAX array.
    agg_dep = f"afterok:{submitted['jax_array']}"
    agg_job = f"ctagg_{name}"[:60]
    agg_script = build_aggregate_script(
        job_name=agg_job, partition=sl.partition, account=sl.account,
        cpus=sl.cpus, mem=sl.mem, time_limit=sl.time, conda_env=sl.conda_env,
        run_dir=run_root, out_root=run_root, dependency=agg_dep)
    _run("aggregate", agg_script, agg_dep)

    if not args.dry_run:
        Path(run_root).mkdir(parents=True, exist_ok=True)
        print(f"\nDependency chain: "
              f"{'sam3(' + submitted['sam3'] + ') -> ' if 'sam3' in submitted else ''}"
              f"{'mvq_lift(' + submitted['mvq_lift'] + ') -> ' if 'mvq_lift' in submitted else ''}"
              f"precompute({submitted['precompute']}) -> "
              f"jax_array({submitted['jax_array']}) -> aggregate({submitted['aggregate']})")
        print(f"Monitor : squeue -u $USER")


if __name__ == "__main__":
    main()
