# ---------------------------------------------------------------------------
# Bout discovery
# ---------------------------------------------------------------------------

def bout_indices(predictions_dir: str) -> list[int]:
    """Sorted bout indices discovered as bout_<idx> dirs under predictions_dir
    (mirrors scripts/run_bout.py::_bout_dirs)."""
    idxs = []
    for d in sorted(glob.glob(os.path.join(predictions_dir, "bout_*"))):
        m = re.match(r"bout_(\d+)$", os.path.basename(d))
        if m:
            idxs.append(int(m.group(1)))
    return sorted(idxs)


def missing_sam3_masks(predictions_dir: str, idxs: list[int]) -> list[int]:
    """Bout indices under predictions_dir lacking a sam3_masks.npz."""
    return [i for i in idxs
            if not os.path.exists(os.path.join(predictions_dir, f"bout_{i:05d}", "sam3_masks.npz"))]


# ---------------------------------------------------------------------------
# Pure sbatch-script builders (unit-tested; no SLURM/filesystem access)
# ---------------------------------------------------------------------------

def _array_spec(idxs: list[int]) -> str:
    """SLURM `--array=` value for a set of (possibly 1-based, non-contiguous)
    bout indices, e.g. [1, 2, 3, 7] -> "1,2,3,7". A comma-joined list (rather
    than a `lo-hi` range) is correct for BOTH contiguous and gappy bout id
    sets, and guarantees `$SLURM_ARRAY_TASK_ID` is always a real bout id."""
    return ",".join(str(i) for i in idxs)


def build_sam3_array_script(
    *,
    job_name: str,
    partition: str,
    account: str,
    cpus: int,
    mem: int,
    gpus: int,
    time_limit: str,
    requeue: bool,
    constraint: str = "",
    conda_env: str,
    idxs: list[int],
    session_dir: str,
    masks_out: str,
    num_animals: int = 2,
    bouts_csv: str = "",
    dependency: str = "",
) -> str:
    """Stage-0 SAM3 mask+identity array (PyTorch env, cu13 CUDA libs).

    One array task per real bout id in `idxs` (bouts are 1-based and may be
    non-contiguous, e.g. no bout_00000 -- see `bout_indices`); `$SLURM_ARRAY_
    TASK_ID` is set to that bout id directly, so `sam3.bout_ids=$SLURM_ARRAY_
    TASK_ID` always names a bout that exists. `sam3.reuse_masks=true` skips
    bouts whose sam3_masks.npz already exists, so this is cheap to resubmit
    and safe even when only a handful of bouts are actually missing masks.

    `bouts_csv` (when set) pins the SAM3 stage to the SAME bout set the jax
    stage reads via cfg.recording.bouts_csv. Without it, sam3_masks.py
    auto-resolves the canonical CSV in the processed dir, which can be a
    STALE bout set (Session11 NewBouts: renumbered bouts would silently pair
    with masks from the wrong frame ranges).
    """
    requeue_line = "#SBATCH --requeue" if requeue else ""
    # Restrict to GPUs big enough for this model. ckpt-all otherwise
    # includes rtx6k/2080ti/p100 (24/11/16 GB) and CPU-only nodes, which
    # either OOM or cannot run the job at all.
    constraint_line = (f"#SBATCH --constraint={constraint}"
                       if constraint else "")
    dependency_line = f"#SBATCH --dependency={dependency}" if dependency else ""
    bouts_csv_arg = f" sam3.bouts_csv={bouts_csv}" if bouts_csv else ""
    return f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --partition={partition}
#SBATCH --account={account}
#SBATCH --time={time_limit}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --gpus={gpus}
#SBATCH --mem={mem}G
#SBATCH --array={_array_spec(idxs)}
#SBATCH --open-mode=append
#SBATCH -o {masks_out}/slurm-sam3-%A_%a.out
{dependency_line}
{requeue_line}
{constraint_line}
set -x
source ~/.bashrc
micromamba activate {conda_env}
export LD_PRELOAD="$CONDA_PREFIX/lib/libstdc++.so.6"
export LD_LIBRARY_PATH="$CONDA_PREFIX/lib/python3.12/site-packages/nvidia/cu13/lib"
# Long bouts (2000+ frames) can OOM SAM3 via allocator fragmentation (GBs
# reserved-but-unallocated). expandable_segments lets PyTorch reclaim them.
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
echo "Node: $SLURMD_NODENAME  job: $SLURM_JOB_ID  task: $SLURM_ARRAY_TASK_ID"
cd {PKG_DIR}
python -u scripts/sam3_masks.py sam3.session_dir={session_dir} sam3.out={masks_out} \\
    sam3.num_animals={num_animals}{bouts_csv_arg} \\
    sam3.bout_ids=${{SLURM_ARRAY_TASK_ID}} sam3.sam3_compile=false sam3.reuse_masks=true
"""


def build_mvq_lift_array_script(
    *,
    job_name: str,
    partition: str,
    account: str,
    cpus: int,
    mem: int,
    gpus: int,
    time_limit: str,
    requeue: bool,
    constraint: str = "",
    conda_env: str,
    idxs: list[int],
    session_dir: str,
    predictions_dir: str,
    run_dir: str,
    checkpoint: str,
    step=None,
    exist_thresh: float = 0.5,
    batch: int = 8,
    merge_dist_units: float = 30.0,
    identity: str = "mask",
    mask_assign_units: float = 10.0,
    anatomy_cfg: str = "configs/anatomy/v1.yaml",
    recording_cfg: str = "configs/recording/session0.yaml",
    bouts_csv: str = "",
    dependency: str = "",
) -> str:
    """mvq lift array (`--lifter mvq`): one task per bout, GPU, JAX env.

    Replaces Stages A+B for this run: each task writes
    `<run_dir>/bouts/bout_<idx:05d>/fly{0,1}/{kp2d,kp3d}.npz` plus sex.json
    from the typed-slot mvq lifter, and the rest of the chain (precompute ->
    IK array -> aggregate) then runs unchanged with `pipeline.lifter=mvq`.

    Placed BEFORE precompute on purpose. The body-scale precompute pools
    `scale.json` over every bout of the recording that is already
    triangulated; running the whole lift array first means it pools all of
    them instead of the one bout it was seeded with (the scale-from-first-bout
    defect, measured 15.5% low on Session0).

    Same env lines as the IK array -- `module load cuda/12.9.1` and the
    LD_LIBRARY_PATH/JAX_PLATFORMS unsets, without which the forward silently
    runs on CPU -- plus `PYTHONPATH=third_party/jarvis_jax:.`, because the
    editable install can point at a DIFFERENT checkout than the one this
    submitter was run from.
    """
    requeue_line = "#SBATCH --requeue" if requeue else ""
    constraint_line = (f"#SBATCH --constraint={constraint}" if constraint else "")
    dependency_line = f"#SBATCH --dependency={dependency}" if dependency else ""
    step_arg = "" if step in (None, "", "null") else f" --step {step}"
    csv_arg = f" --bouts-csv {shlex.quote(str(bouts_csv))}" if bouts_csv else ""
    return f"""#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --partition={partition}
#SBATCH --account={account}
#SBATCH --time={time_limit}
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --gpus={gpus}
#SBATCH --mem={mem}G
#SBATCH --array={_array_spec(idxs)}
#SBATCH --open-mode=append
#SBATCH -o {run_dir}/slurm-mvqlift-%A_%a.out
{dependency_line}
{requeue_line}
{constraint_line}
set -x
source ~/.bashrc
micromamba activate {conda_env}
module load cuda/12.9.1
export LD_PRELOAD="$CONDA_PREFIX/lib/libstdc++.so.6"   # cv2 (video reads)
unset LD_LIBRARY_PATH                       # let JAX use its bundled CUDA wheels
unset JAX_PLATFORMS                         # NEVER inherit JAX_PLATFORMS=cpu from the submit env
export XLA_PYTHON_CLIENT_MEM_FRACTION=0.9
echo "Node: $SLURMD_NODENAME  job: $SLURM_JOB_ID  task: $SLURM_ARRAY_TASK_ID"
nvidia-smi -L
cd {PROJECT_DIR}
mkdir -p {run_dir}
PYTHONPATH=third_party/jarvis_jax:. python -u scripts/mvq_lift_bout.py \\
    --session-dir {session_dir} --predictions-dir {predictions_dir} \\
    --out {run_dir} --bout ${{SLURM_ARRAY_TASK_ID}} \\
    --run {checkpoint}{step_arg} --exist-thresh {exist_thresh} --batch {batch} \\
    --merge-dist-units {merge_dist_units} \\
    --identity {identity} --mask-assign-units {mask_assign_units} \\
    --anatomy {anatomy_cfg} --recording-cfg {recording_cfg}{csv_arg}
"""


